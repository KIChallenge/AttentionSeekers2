"""Score the baseline per PREREGISTRATION.md section 8 and 9.

  python -m svforecast.score            # writes data/scores.json and data/scores.md
"""

from __future__ import annotations

import json
import random
from collections import Counter, defaultdict
from pathlib import Path

from .forecast import TARGETS, category, forecast_a, forecast_b, load_episodes, pool_for, status_quo

ROOT = Path(__file__).resolve().parents[2]
BURN_IN = 10
B = 2000
SEED = 20261105


def brier(probs: dict, cat: str, cats: list[str], target: str) -> float:
    if target == "binary":
        return (probs["enacted"] - (1.0 if cat == "enacted" else 0.0)) ** 2
    return sum((probs[c] - (1.0 if c == cat else 0.0)) ** 2 for c in cats)


def score_rows(episodes, target, exclude_title_only=False):
    cats = TARGETS[target]
    rows = []
    usable = [e for e in episodes if not (exclude_title_only and e.get("title_link_only"))]
    for e in usable:
        cat = category(e["outcome"], target)
        if e["censored"] or cat is None:
            continue
        if target == "three" and not e.get("three_class_ok", True):
            continue
        pool = pool_for(usable, e["first_draft_date"], exclude=e["episode_id"])
        n_pool = sum(1 for p in pool if category(p["outcome"], target) is not None
                     and (target == "binary" or p.get("three_class_ok", True)))
        if n_pool < BURN_IN:
            continue
        fa, fb, fs = forecast_a(e, pool, target), forecast_b(e, pool, target), status_quo(e, pool, target)
        rows.append({"episode_id": e["episode_id"], "gp": e["gp"], "date": e["first_draft_date"], "cat": cat,
                     "level_a": fa.level, "n_a": fa.n, "n_pool": n_pool,
                     "bs_a": brier(fa.probs, cat, cats, target), "bs_b": brier(fb.probs, cat, cats, target),
                     "bs_sq": brier(fs.probs, cat, cats, target)})
    return rows


def summarise(rows):
    n = len(rows)
    if n == 0:
        return None
    m = {k: sum(r[k] for r in rows) / n for k in ("bs_a", "bs_b", "bs_sq")}
    out = {"n": n, "bs_a": m["bs_a"], "bs_b": m["bs_b"], "bs_sq": m["bs_sq"]}
    for f in ("a", "b"):
        out[f"bss_{f}"] = 1 - m[f"bs_{f}"] / m["bs_sq"] if m["bs_sq"] > 0 else float("nan")
        out[f"d_{f}"] = m["bs_sq"] - m[f"bs_{f}"]
    return out


def pct(xs, q):
    xs = sorted(xs)
    i = q * (len(xs) - 1)
    lo, hi = int(i), min(int(i) + 1, len(xs) - 1)
    return xs[lo] + (xs[hi] - xs[lo]) * (i - lo)


def bootstrap(rows, by: str):
    rng = random.Random(SEED)
    if by == "gp":
        groups = defaultdict(list)
        for r in rows:
            groups[r["gp"]].append(r)
        units = list(groups.values())
    else:
        units = [[r] for r in rows]
    stats = defaultdict(list)
    for _ in range(B):
        sample = [r for u in (rng.choice(units) for _ in units) for r in u]
        s = summarise(sample)
        for k, v in s.items():
            if k != "n":
                stats[k].append(v)
    return {k: (pct(v, 0.05), pct(v, 0.95)) for k, v in stats.items()}, len(units)


def verdict(ci):
    lo, hi = ci
    if lo > 0:
        return "class membership beats the status-quo baseline"
    if hi < 0:
        return "class membership is worse than the status-quo baseline"
    return "inconclusive at this N"


def run():
    eps = load_episodes()
    result = {"label_distribution_episodes": Counter(e["outcome"] for e in eps)}
    for variant, excl in (("main", False), ("without_title_only_links", True)):
        for target in ("binary", "three"):
            rows = score_rows(eps, target, excl)
            s = summarise(rows)
            if s is None:
                result[f"{variant}/{target}"] = {"n": 0}
                continue
            ci_gp, n_gp = bootstrap(rows, "gp")
            ci_ep, _ = bootstrap(rows, "episode")
            s.update({"ci90_gp_bootstrap": ci_gp, "n_gp_clusters": n_gp, "ci90_episode_bootstrap": ci_ep,
                      "verdict_A_primary": verdict(ci_gp["d_a"]), "verdict_B": verdict(ci_gp["d_b"]),
                      "levels_used_A": Counter(r["level_a"] for r in rows),
                      "scored_by_gp": Counter(r["gp"] for r in rows),
                      "category_counts": Counter(r["cat"] for r in rows)})
            result[f"{variant}/{target}"] = s
            if variant == "main" and target == "binary":
                (ROOT / "data" / "scored_rows_binary.jsonl").write_text("\n".join(json.dumps(r) for r in rows) + "\n")
    (ROOT / "data" / "scores.json").write_text(json.dumps(result, indent=1, ensure_ascii=False, default=list))
    lines = ["# Baseline scores (generated by `python -m svforecast.score`)", ""]
    for k, s in result.items():
        if k == "label_distribution_episodes":
            lines.append(f"Episode labels: {dict(s)}")
            lines.append("")
            continue
        if not s.get("n"):
            lines.append(f"## {k}: no scorable episodes")
            continue
        g, e = s["ci90_gp_bootstrap"], s["ci90_episode_bootstrap"]
        f = lambda v: f"{v:.3f}"
        lines += [f"## {k} (N scored = {s['n']}, GP clusters = {s['n_gp_clusters']})", "",
                  "| | Brier | 90% CI (GP boot) | 90% CI (episode boot) |", "|---|---|---|---|",
                  f"| A: hierarchical class | {f(s['bs_a'])} | {f(g['bs_a'][0])} to {f(g['bs_a'][1])} | {f(e['bs_a'][0])} to {f(e['bs_a'][1])} |",
                  f"| B: weighted analogs | {f(s['bs_b'])} | {f(g['bs_b'][0])} to {f(g['bs_b'][1])} | {f(e['bs_b'][0])} to {f(e['bs_b'][1])} |",
                  f"| status quo | {f(s['bs_sq'])} | {f(g['bs_sq'][0])} to {f(g['bs_sq'][1])} | {f(e['bs_sq'][0])} to {f(e['bs_sq'][1])} |",
                  f"| BSS A | {f(s['bss_a'])} | {f(g['bss_a'][0])} to {f(g['bss_a'][1])} | {f(e['bss_a'][0])} to {f(e['bss_a'][1])} |",
                  f"| BSS B | {f(s['bss_b'])} | {f(g['bss_b'][0])} to {f(g['bss_b'][1])} | {f(e['bss_b'][0])} to {f(e['bss_b'][1])} |",
                  f"| D = BS_sq - BS_A | {f(s['d_a'])} | {f(g['d_a'][0])} to {f(g['d_a'][1])} | {f(e['d_a'][0])} to {f(e['d_a'][1])} |",
                  f"| D = BS_sq - BS_B | {f(s['d_b'])} | {f(g['d_b'][0])} to {f(g['d_b'][1])} | {f(e['d_b'][0])} to {f(e['d_b'][1])} |",
                  "", f"Verdict (A, primary rule): **{s['verdict_A_primary']}**. Verdict (B): {s['verdict_B']}.",
                  f"Class levels used by A: {dict(s['levels_used_A'])}. Scored per GP: {dict(s['scored_by_gp'])}. "
                  f"Outcome categories: {dict(s['category_counts'])}.", ""]
    (ROOT / "data" / "scores.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    run()
